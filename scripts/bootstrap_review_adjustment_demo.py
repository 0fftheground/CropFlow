def _list_open_reviews(session: Session, planting_plan_id: int) -> list[ReviewSummary]:
    reviews = list(
        session.scalars(
            select(ReviewRequest)
            .where(ReviewRequest.planting_plan_id == planting_plan_id)
            .where(ReviewRequest.status == "open")
            .order_by(ReviewRequest.id.asc()),
        ),
    )
    task_intents = {
        item.id: item
        for item in session.scalars(
            select(TaskIntent).where(TaskIntent.planting_plan_id == planting_plan_id).order_by(TaskIntent.id.asc())
        )
    }
    return [
        ReviewSummary(
            id=int(item.id),
            review_type=item.review_type,
            task_subtype=task_intents.get(item.source_entity_id).task_subtype
            if item.source_entity_type in {"task_intent", "cf_task_intent"} and item.source_entity_id in task_intents
            else None,
            title=item.title,
            status=item.status,
        )
        for item in reviews
    ]


def _serialize_summary(summary: BootstrapSummary) -> dict[str, Any]:
    data = asdict(summary)
    data["next_step"] = {
        "resolved_by_examples": ["reviewer-demo", "联调复核员"],
        "review_request_ids": {
            item.task_subtype or item.review_type: item.id for item in summary.open_reviews
        },
    }
    return data


def _sync_id_sequence(session: Session, table_name: str) -> None:
    session.execute(
        text(
            f"""
            select setval(
                pg_get_serial_sequence('{table_name}', 'id'),
                coalesce((select max(id) from {table_name}), 1),
                true
            )
            """
        ),
    )


